import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptsDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptsDirectory, "..");
const docsDirectory = path.join(projectRoot, "src", "content", "docs");
const outputPath = path.join(docsDirectory, "generated.ts");

const fileNames = (await readdir(docsDirectory))
  .filter((fileName) => fileName.endsWith(".md"))
  .sort();

const entries = await Promise.all(
  fileNames.map(async (fileName) => [
    fileName.slice(0, -3),
    await readFile(path.join(docsDirectory, fileName), "utf8"),
  ]),
);

const generatedSource = `// Generated by scripts/generate-docs-content.mjs. Do not edit manually.
const docsContent = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;

export const DOC_SLUGS = Object.keys(docsContent) as Array<keyof typeof docsContent>;

export function getDocContent(slug: string): string | null {
  return docsContent[slug as keyof typeof docsContent] ?? null;
}
`;

await writeFile(outputPath, generatedSource, "utf8");
